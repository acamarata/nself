func TestDetect_MultipleArtifacts(t *testing.T) {
	dir := t.TempDir()

	// Plant all 5 artifacts
	writeFile(t, filepath.Join(dir, "docker-compose.yml"), "# Generated by nself\nversion: '3'\n")
	writeFile(t, filepath.Join(dir, ".env"), "NSELF_VERSION=0.9.9\n")
	mkDir(t, filepath.Join(dir, "nginx"))
	writeFile(t, filepath.Join(dir, ".nself", "config"), "version=0.9.9\n")
	writeFile(t, filepath.Join(dir, "nself.sh"), "#!/bin/bash\n")

	artifacts := Detect(dir)
	if len(artifacts) != 5 {
		t.Errorf("expected 5 artifacts, got %d: %v", len(artifacts), artifacts)
	}
}

// containsPath checks whether any artifact in the slice has the given path.
func containsPath(artifacts []LegacyArtifact, path string) bool {
	for _, a := range artifacts {
		if a.Path == path {
			return true
		}
	}
	return false
}
