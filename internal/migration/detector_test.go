func TestDetect_ComposeFile(t *testing.T) {
	tests := []struct {
		name       string
		content    string
		wantDetect bool
	}{
		{
			name:       "v1 generated compose",
			content:    "# Generated by nself\nversion: '3'\n",
			wantDetect: true,
		},
		{
			name:       "v2 generated compose",
			content:    "# Generated by nself\n# nself v2\nversion: '3'\n",
			wantDetect: false,
		},
		{
			name:       "unrelated compose",
			content:    "version: '3'\nservices:\n",
			wantDetect: false,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			writeFile(t, filepath.Join(dir, "docker-compose.yml"), tc.content)
			artifacts := Detect(dir)
			got := containsPath(artifacts, "docker-compose.yml")
			if got != tc.wantDetect {
				t.Errorf("wantDetect=%v, got=%v (artifacts=%v)", tc.wantDetect, got, artifacts)
			}
		})
	}
}

