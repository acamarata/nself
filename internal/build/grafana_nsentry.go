// Package build — grafana_nsentry.go: Auto-provisions Grafana datasource +
// dashboards for the ɳSentry plugin bundle.
//
// When the ɳSentry bundle is licensed and any of its plugins are installed,
// `nself build` must emit:
//   - monitoring/grafana/provisioning/datasources/nsentry.yaml — datasource
//     entry referencing the existing Prometheus datasource so panels resolve.
//   - monitoring/grafana/provisioning/dashboards/nsentry.yaml — dashboard
//     provisioning entry pointing at the dashboard directory.
//   - monitoring/grafana/dashboards/nsentry/<slug>.json — one dashboard JSON
//     per installed ɳSentry plugin (uptime, status, incident, alert-router,
//     slo, synthetic, rum, and any expansion plugins).
//
// T04 wires the `nself-status-page` plugin's status summary endpoint
// (HTTP GET <host>:3832/status) into the status-page dashboard via a Grafana
// text panel that renders a status-summary link, so operators land directly
// on the public status page from the bundle overview.
//
// Behavior:
//   - Detection reuses the canonical ɳSentry plugin list from prometheus.go
//     (nsentryPlugins) — single source of truth for which plugins exist.
//   - Zero ɳSentry plugins installed → no files emitted, no directories
//     created. Caller invokes WriteNSentryGrafanaProvisioning regardless;
//     it is a no-op when nothing is installed.
//   - Idempotent: re-running with the same set of installed plugins yields
//     byte-identical files (deterministic JSON marshaling + stable key order).
//   - Adding a new ɳSentry plugin: append to nsentryPlugins in prometheus.go
//     and add a dashboard template entry below (dashboardTitles map).
//
// This file holds installed-plugin detection and the two static provisioning
// YAML renderers. The dashboard JSON struct + renderer moved to
// grafana_nsentry_dashboard.go, and the write-to-disk orchestration moved to
// grafana_nsentry_write.go — both split out (CLI-R12) as pure moves from this
// file.
package build

import (
	"os"
	"path/filepath"
	"sort"
)

// dashboardTitles maps each ɳSentry plugin slug (as defined in
// nsentryPlugins in prometheus.go) to its dashboard display title.
// New plugins MUST be added here when added to nsentryPlugins; otherwise
// they will be skipped silently during provisioning.
var dashboardTitles = map[string]string{
	"alert-router":      "ɳSentry — Alert Router",
	"incident-mgmt":     "ɳSentry — Incident Management",
	"rum":               "ɳSentry — Real-User Monitoring",
	"slo-tracker":       "ɳSentry — SLO Tracker",
	"status-page":       "ɳSentry — Status Page",
	"synthetic-monitor": "ɳSentry — Synthetic Monitor",
	"uptime-monitor":    "ɳSentry — Uptime Monitor",
	"errors":            "ɳSentry — Error Tracking",
	"cron-monitor":      "ɳSentry — Cron Monitor",
	"oncall":            "ɳSentry — On-Call Rotation",
	"crash":             "ɳSentry — Crash Reporting",
	"anomaly":           "ɳSentry — Anomaly Detection",
	"audit":             "ɳSentry — Audit Log",
}

// installedNSentryForGrafana returns the subset of nsentryPlugins that have a
// plugin.json under pluginDir. Reuses the same detection rule as
// NSentryScrapeTargets so a single source-of-truth governs "installed".
func installedNSentryForGrafana(pluginDir string) []nsentryPlugin {
	if pluginDir == "" {
		return nil
	}
	installed := make([]nsentryPlugin, 0, len(nsentryPlugins))
	for _, p := range nsentryPlugins {
		if _, err := os.Stat(filepath.Join(pluginDir, p.name, "plugin.json")); err != nil {
			continue
		}
		installed = append(installed, p)
	}
	// Stable alphabetical order by slug so generated files are deterministic.
	sort.Slice(installed, func(i, j int) bool { return installed[i].slug < installed[j].slug })
	return installed
}

// RenderNSentryDatasourceYAML returns the bytes for
// grafana/provisioning/datasources/nsentry.yaml. The datasource simply
// references the existing Prometheus datasource (provisioned by the core
// monitoring bundle) — the ɳSentry dashboards consume it via the
// ${DS_PROMETHEUS} variable. Emitting the file under the ɳSentry namespace
// makes provisioning per-bundle: uninstalling the bundle removes only the
// nsentry.yaml, leaving the core Prometheus datasource untouched.
//
// Returns nil when no ɳSentry plugin is installed under pluginDir so callers
// can skip writing the file cleanly.
func RenderNSentryDatasourceYAML(pluginDir string) []byte {
	installed := installedNSentryForGrafana(pluginDir)
	if len(installed) == 0 {
		return nil
	}
	// Static YAML — no per-plugin variation. Listed under apiVersion: 1
	// per Grafana 10.x provisioning schema.
	return []byte(`# Generated by nself build — DO NOT HAND EDIT
# ɳSentry datasource provisioning (S12.T02).
# References the core Prometheus datasource installed by the monitoring bundle.
apiVersion: 1

datasources:
  - name: nSentry-Prometheus
    type: prometheus
    access: proxy
    url: http://prometheus:9090
    isDefault: false
    uid: nsentry-prometheus
    jsonData:
      timeInterval: 15s
      httpMethod: POST
    editable: false
`)
}

// RenderNSentryDashboardProvisioning returns the YAML pointing Grafana's
// dashboard provisioner at the per-plugin dashboard JSON files emitted by
// RenderNSentryDashboard. Returns nil when no ɳSentry plugin is installed.
func RenderNSentryDashboardProvisioning(pluginDir string) []byte {
	if len(installedNSentryForGrafana(pluginDir)) == 0 {
		return nil
	}
	return []byte(`# Generated by nself build — DO NOT HAND EDIT
# ɳSentry dashboard provisioning (S12.T02).
apiVersion: 1

providers:
  - name: 'nsentry'
    orgId: 1
    folder: 'ɳSentry'
    type: file
    disableDeletion: false
    updateIntervalSeconds: 30
    allowUiUpdates: false
    options:
      path: /var/lib/grafana/dashboards/nsentry
`)
}
