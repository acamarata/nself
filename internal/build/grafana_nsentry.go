// Package build — grafana_nsentry.go: Auto-provisions Grafana datasource +
// dashboards for the ɳSentry plugin bundle.
//
// S12.T02 + S12.T04 (P100 v1.1.0): When the ɳSentry bundle is licensed and any
// of its plugins are installed, `nself build` must emit:
//   - monitoring/grafana/provisioning/datasources/nsentry.yaml — datasource
//     entry referencing the existing Prometheus datasource so panels resolve.
//   - monitoring/grafana/provisioning/dashboards/nsentry.yaml — dashboard
//     provisioning entry pointing at the dashboard directory.
//   - monitoring/grafana/dashboards/nsentry/<slug>.json — one dashboard JSON
//     per installed ɳSentry plugin (uptime, status, incident, alert-router,
//     slo, synthetic, rum, and any expansion plugins).
//
// T04 wires the `nself-status-page` plugin's status summary endpoint
// (HTTP GET <host>:3832/status) into the status-page dashboard via a Grafana
// text panel that renders a status-summary link, so operators land directly
// on the public status page from the bundle overview.
//
// Behavior:
//   - Detection reuses the canonical ɳSentry plugin list from prometheus.go
//     (nsentryPlugins) — single source of truth for which plugins exist.
//   - Zero ɳSentry plugins installed → no files emitted, no directories
//     created. Caller invokes WriteNSentryGrafanaProvisioning regardless;
//     it is a no-op when nothing is installed.
//   - Idempotent: re-running with the same set of installed plugins yields
//     byte-identical files (deterministic JSON marshaling + stable key order).
//   - Adding a new ɳSentry plugin: append to nsentryPlugins in prometheus.go
//     and add a dashboard template entry below (dashboardTitles map).
package build

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
)

// dashboardTitles maps each ɳSentry plugin slug (as defined in
// nsentryPlugins in prometheus.go) to its dashboard display title.
// New plugins MUST be added here when added to nsentryPlugins; otherwise
// they will be skipped silently during provisioning.
var dashboardTitles = map[string]string{
	"alert-router":      "ɳSentry — Alert Router",
	"incident-mgmt":     "ɳSentry — Incident Management",
	"rum":               "ɳSentry — Real-User Monitoring",
	"slo-tracker":       "ɳSentry — SLO Tracker",
	"status-page":       "ɳSentry — Status Page",
	"synthetic-monitor": "ɳSentry — Synthetic Monitor",
	"uptime-monitor":    "ɳSentry — Uptime Monitor",
	"errors":            "ɳSentry — Error Tracking",
	"cron-monitor":      "ɳSentry — Cron Monitor",
	"oncall":            "ɳSentry — On-Call Rotation",
	"crash":             "ɳSentry — Crash Reporting",
	"anomaly":           "ɳSentry — Anomaly Detection",
	"audit":             "ɳSentry — Audit Log",
}

// installedNSentryForGrafana returns the subset of nsentryPlugins that have a
// plugin.json under pluginDir. Reuses the same detection rule as
// NSentryScrapeTargets so a single source-of-truth governs "installed".
func installedNSentryForGrafana(pluginDir string) []nsentryPlugin {
	if pluginDir == "" {
		return nil
	}
	installed := make([]nsentryPlugin, 0, len(nsentryPlugins))
	for _, p := range nsentryPlugins {
		if _, err := os.Stat(filepath.Join(pluginDir, p.name, "plugin.json")); err != nil {
			continue
		}
		installed = append(installed, p)
	}
	// Stable alphabetical order by slug so generated files are deterministic.
	sort.Slice(installed, func(i, j int) bool { return installed[i].slug < installed[j].slug })
	return installed
}

// RenderNSentryDatasourceYAML returns the bytes for
// grafana/provisioning/datasources/nsentry.yaml. The datasource simply
// references the existing Prometheus datasource (provisioned by the core
// monitoring bundle) — the ɳSentry dashboards consume it via the
// ${DS_PROMETHEUS} variable. Emitting the file under the ɳSentry namespace
// makes provisioning per-bundle: uninstalling the bundle removes only the
// nsentry.yaml, leaving the core Prometheus datasource untouched.
//
// Returns nil when no ɳSentry plugin is installed under pluginDir so callers
// can skip writing the file cleanly.
func RenderNSentryDatasourceYAML(pluginDir string) []byte {
	installed := installedNSentryForGrafana(pluginDir)
	if len(installed) == 0 {
		return nil
	}
	// Static YAML — no per-plugin variation. Listed under apiVersion: 1
	// per Grafana 10.x provisioning schema.
	return []byte(`# Generated by nself build — DO NOT HAND EDIT
# ɳSentry datasource provisioning (S12.T02).
# References the core Prometheus datasource installed by the monitoring bundle.
apiVersion: 1

datasources:
  - name: nSentry-Prometheus
    type: prometheus
    access: proxy
    url: http://prometheus:9090
    isDefault: false
    uid: nsentry-prometheus
    jsonData:
      timeInterval: 15s
      httpMethod: POST
    editable: false
`)
}

// RenderNSentryDashboardProvisioning returns the YAML pointing Grafana's
// dashboard provisioner at the per-plugin dashboard JSON files emitted by
// RenderNSentryDashboard. Returns nil when no ɳSentry plugin is installed.
func RenderNSentryDashboardProvisioning(pluginDir string) []byte {
	if len(installedNSentryForGrafana(pluginDir)) == 0 {
		return nil
	}
	return []byte(`# Generated by nself build — DO NOT HAND EDIT
# ɳSentry dashboard provisioning (S12.T02).
apiVersion: 1

providers:
  - name: 'nsentry'
    orgId: 1
    folder: 'ɳSentry'
    type: file
    disableDeletion: false
    updateIntervalSeconds: 30
    allowUiUpdates: false
    options:
      path: /var/lib/grafana/dashboards/nsentry
`)
}

// dashboardPanel is the minimal Grafana 10.x panel struct we emit. Real
// dashboards have dozens of fields; we ship a focused subset (request rate
// + error rate + p95 latency) per plugin that is valid JSON and renders.
type dashboardPanel struct {
	ID          int                 `json:"id"`
	Type        string              `json:"type"`
	Title       string              `json:"title"`
	Datasource  map[string]string   `json:"datasource"`
	GridPos     map[string]int      `json:"gridPos"`
	Targets     []map[string]string `json:"targets,omitempty"`
	Options     map[string]any      `json:"options,omitempty"`
	FieldConfig map[string]any      `json:"fieldConfig,omitempty"`
	Content     string              `json:"content,omitempty"` // text panel HTML
	Mode        string              `json:"mode,omitempty"`    // text panel: "html"|"markdown"
}

// dashboard is the top-level Grafana dashboard JSON envelope we emit.
type dashboard struct {
	UID           string            `json:"uid"`
	Title         string            `json:"title"`
	SchemaVersion int               `json:"schemaVersion"`
	Version       int               `json:"version"`
	Editable      bool              `json:"editable"`
	Tags          []string          `json:"tags"`
	Time          map[string]string `json:"time"`
	Refresh       string            `json:"refresh"`
	Panels        []dashboardPanel  `json:"panels"`
}

// RenderNSentryDashboard returns the dashboard JSON bytes for a single ɳSentry
// plugin slug. The dashboard contains three panels with PromQL queries filtered
// by bundle="nsentry" and plugin="<slug>":
//
//  1. Request rate (rate(http_requests_total{...}[5m]))
//  2. Error rate  (rate(http_requests_total{status=~"5.."}[5m]))
//  3. p95 latency (histogram_quantile(0.95, ...))
//
// When slug == "status-page", a fourth text panel (T04) is appended that
// links operators directly to the public status summary endpoint exposed by
// the nself-status-page plugin (GET <host>:3832/status). The link text uses
// a Grafana variable so the host substitutes correctly per environment.
func RenderNSentryDashboard(slug string) ([]byte, error) {
	title, ok := dashboardTitles[slug]
	if !ok {
		return nil, fmt.Errorf("grafana_nsentry: unknown plugin slug %q (add to dashboardTitles)", slug)
	}

	ds := map[string]string{"type": "prometheus", "uid": "nsentry-prometheus"}
	labelFilter := fmt.Sprintf(`{bundle="nsentry",plugin="%s"}`, slug)

	panels := []dashboardPanel{
		{
			ID:         1,
			Type:       "timeseries",
			Title:      "Request Rate",
			Datasource: ds,
			GridPos:    map[string]int{"h": 8, "w": 12, "x": 0, "y": 0},
			Targets: []map[string]string{
				{
					"refId": "A",
					"expr":  "sum(rate(http_requests_total" + labelFilter + "[5m]))",
				},
			},
		},
		{
			ID:         2,
			Type:       "timeseries",
			Title:      "Error Rate (5xx)",
			Datasource: ds,
			GridPos:    map[string]int{"h": 8, "w": 12, "x": 12, "y": 0},
			Targets: []map[string]string{
				{
					"refId": "A",
					"expr":  `sum(rate(http_requests_total{bundle="nsentry",plugin="` + slug + `",status=~"5.."}[5m]))`,
				},
			},
		},
		{
			ID:         3,
			Type:       "timeseries",
			Title:      "p95 Latency",
			Datasource: ds,
			GridPos:    map[string]int{"h": 8, "w": 24, "x": 0, "y": 8},
			Targets: []map[string]string{
				{
					"refId": "A",
					"expr":  `histogram_quantile(0.95, sum by (le) (rate(http_request_duration_seconds_bucket{bundle="nsentry",plugin="` + slug + `"}[5m])))`,
				},
			},
		},
	}

	// T04 — status-page integration: link to the public /status endpoint.
	// The plugin binds on port 3832 (F10-PORT-REGISTRY) and exposes a
	// summary view at GET /status. We embed a text panel so the dashboard
	// surfaces this immediately rather than burying it in a runbook.
	if slug == "status-page" {
		panels = append(panels, dashboardPanel{
			ID:         4,
			Type:       "text",
			Title:      "Public Status Page",
			Datasource: nil,
			GridPos:    map[string]int{"h": 4, "w": 24, "x": 0, "y": 16},
			Mode:       "markdown",
			Content: "Public status summary served by " +
				"`nself-status-page` on port **3832**.\n\n" +
				"- Live page: [http://${__org.name}:3832/status](http://${__org.name}:3832/status)\n" +
				"- RSS feed: [http://${__org.name}:3832/status.rss](http://${__org.name}:3832/status.rss)\n" +
				"- Atom feed: [http://${__org.name}:3832/status.atom](http://${__org.name}:3832/status.atom)\n",
		})
	}

	d := dashboard{
		UID:           "nsentry-" + slug,
		Title:         title,
		SchemaVersion: 38,
		Version:       1,
		Editable:      false,
		Tags:          []string{"nsentry", slug},
		Time:          map[string]string{"from": "now-6h", "to": "now"},
		Refresh:       "30s",
		Panels:        panels,
	}

	// Marshal with stable indent so files round-trip byte-identically on
	// re-build. json.Marshal already orders struct fields by declaration;
	// maps inside fields use canonical-key emission via Go's stdlib (Go
	// 1.12+ sorts map keys in json.Marshal output).
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(d); err != nil {
		return nil, fmt.Errorf("grafana_nsentry: marshal dashboard %s: %w", slug, err)
	}
	return buf.Bytes(), nil
}

// WriteNSentryGrafanaProvisioning emits the full Grafana auto-provisioning
// tree for the installed ɳSentry plugins under pluginDir. Writes:
//
//	<workdir>/monitoring/grafana/provisioning/datasources/nsentry.yaml
//	<workdir>/monitoring/grafana/provisioning/dashboards/nsentry.yaml
//	<workdir>/monitoring/grafana/dashboards/nsentry/<slug>.json   (one per installed plugin)
//
// Returns the count of files written (0 when no ɳSentry plugin installed).
// Idempotent: a second call with the same on-disk state produces
// byte-identical output (no .tmp leftovers, atomic rename pattern reused
// from loki.go's atomicWrite).
func WriteNSentryGrafanaProvisioning(workdir, pluginDir string) (int, error) {
	installed := installedNSentryForGrafana(pluginDir)
	if len(installed) == 0 {
		return 0, nil
	}

	dsBytes := RenderNSentryDatasourceYAML(pluginDir)
	dashProvBytes := RenderNSentryDashboardProvisioning(pluginDir)
	if dsBytes == nil || dashProvBytes == nil {
		// Defensive: installedNSentryForGrafana returned non-empty so
		// these renderers should too. Bail out if a future refactor
		// breaks the invariant.
		return 0, fmt.Errorf("grafana_nsentry: renderer returned nil despite installed plugins")
	}

	dsPath := filepath.Join(workdir, "monitoring", "grafana", "provisioning", "datasources", "nsentry.yaml")
	dashProvPath := filepath.Join(workdir, "monitoring", "grafana", "provisioning", "dashboards", "nsentry.yaml")
	dashDir := filepath.Join(workdir, "monitoring", "grafana", "dashboards", "nsentry")

	if err := os.MkdirAll(filepath.Dir(dsPath), 0o755); err != nil {
		return 0, fmt.Errorf("grafana_nsentry: mkdir %s: %w", filepath.Dir(dsPath), err)
	}
	if err := os.MkdirAll(filepath.Dir(dashProvPath), 0o755); err != nil {
		return 0, fmt.Errorf("grafana_nsentry: mkdir %s: %w", filepath.Dir(dashProvPath), err)
	}
	if err := os.MkdirAll(dashDir, 0o755); err != nil {
		return 0, fmt.Errorf("grafana_nsentry: mkdir %s: %w", dashDir, err)
	}

	written := 0
	if err := atomicWrite(dsPath, dsBytes, 0o644); err != nil {
		return written, err
	}
	written++
	if err := atomicWrite(dashProvPath, dashProvBytes, 0o644); err != nil {
		return written, err
	}
	written++

	for _, p := range installed {
		body, err := RenderNSentryDashboard(p.slug)
		if err != nil {
			return written, err
		}
		path := filepath.Join(dashDir, p.slug+".json")
		if err := atomicWrite(path, body, 0o644); err != nil {
			return written, err
		}
		written++
	}
	return written, nil
}
