package commands

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/nself-org/cli/internal/config"
	"github.com/nself-org/cli/internal/ui"

	"github.com/spf13/cobra"
)

var wafCmd = &cobra.Command{
	Use:   "waf",
	Short: "Manage the Web Application Firewall (Coraza + OWASP CRS)",
	Long: `Manage the Coraza WAF integrated with nginx.

Subcommands:
  enable    Enable the WAF in detection mode
  mode      Switch between detection and blocking mode
  report    Show recent WAF events`,
	RunE: func(cmd *cobra.Command, args []string) error {
		return cmd.Help()
	},
}

var wafEnableCmd = &cobra.Command{
	Use:   "enable",
	Short: "Enable the WAF in detection mode",
	Long: `Enable the Coraza WAF with OWASP Core Rule Set in DetectionOnly mode.
Requests are logged but not blocked. Use 'nself waf mode blocking' to enforce.`,
	RunE: runWAFEnable,
}

var wafModeCmd = &cobra.Command{
	Use:   "mode <detection|blocking>",
	Short: "Set WAF enforcement mode",
	Long: `Switch the WAF between detection (log only) and blocking (enforce) mode.

  detection  — log suspicious requests but allow them through
  blocking   — block requests matching OWASP CRS rules`,
	Args: cobra.ExactArgs(1),
	RunE: runWAFMode,
}

var wafReportCmd = &cobra.Command{
	Use:   "report",
	Short: "Show recent WAF events",
	Long: `Display recent WAF events from nginx error logs.

Use --since to filter by time window (default: 24h).`,
	RunE: runWAFReport,
}

func init() {
	wafReportCmd.Flags().String("since", "24h", "Time window for report (e.g., 1h, 24h, 7d)")
	wafCmd.AddCommand(wafEnableCmd)
	wafCmd.AddCommand(wafModeCmd)
	wafCmd.AddCommand(wafReportCmd)
	RootCmd.AddCommand(wafCmd)
}

func runWAFEnable(cmd *cobra.Command, args []string) error {
	ui.CommandHeader("nself waf enable", "Enable WAF (Coraza + OWASP CRS)")

	cwd, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("getting working directory: %w", err)
	}
	workdir, err := config.FindNSelfRoot(cwd)
	if err != nil {
		return fmt.Errorf("no nself project found: run 'nself init' first")
	}

	// Create WAF directories.
	wafDir := filepath.Join(workdir, "nginx", "waf")
	crsDir := filepath.Join(wafDir, "crs")
	for _, d := range []string{wafDir, crsDir} {
		if mkErr := os.MkdirAll(d, 0755); mkErr != nil {
			return fmt.Errorf("creating WAF directory %s: %w", d, mkErr)
		}
	}

	// Write Coraza main config.
	corazaConf := `# Coraza WAF Configuration
# Generated by nself waf enable

SecRuleEngine DetectionOnly
SecRequestBodyAccess On
SecRequestBodyLimit 13107200
SecResponseBodyAccess Off

# OWASP CRS
Include /etc/nginx/waf/crs/*.conf

# Custom rules
Include /etc/nginx/waf/custom.conf

# Logging — waf_event label for Loki
SecAuditEngine RelevantOnly
SecAuditLogRelevantStatus "^(?:5|4(?!04))"
SecAuditLogType Serial
SecAuditLog /var/log/nginx/waf_audit.log
`
	corazaPath := filepath.Join(wafDir, "coraza.conf")
	if err := os.WriteFile(corazaPath, []byte(corazaConf), 0644); err != nil {
		return fmt.Errorf("writing coraza.conf: %w", err)
	}

	// Write empty custom rules file.
	customPath := filepath.Join(wafDir, "custom.conf")
	if _, err := os.Stat(customPath); os.IsNotExist(err) {
		custom := "# Custom WAF rules\n# Add rules here to extend or override OWASP CRS\n"
		if err := os.WriteFile(customPath, []byte(custom), 0644); err != nil {
			return fmt.Errorf("writing custom.conf: %w", err)
		}
	}

	ui.Success("WAF enabled in DetectionOnly mode.")
	ui.Info("WAF config: nginx/waf/coraza.conf")
	ui.Info("Custom rules: nginx/waf/custom.conf")
	ui.Info("Run 'nself build && nself restart nginx' to apply.")
	ui.Info("Use 'nself waf mode blocking' to enforce rules.")
	return nil
}

func runWAFMode(cmd *cobra.Command, args []string) error {
	mode := strings.ToLower(args[0])
	if mode != "detection" && mode != "blocking" {
		return fmt.Errorf("invalid mode %q: use 'detection' or 'blocking'", mode)
	}

	ui.CommandHeader("nself waf mode", fmt.Sprintf("Set WAF mode to %s", mode))

	cwd, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("getting working directory: %w", err)
	}
	workdir, err := config.FindNSelfRoot(cwd)
	if err != nil {
		return fmt.Errorf("no nself project found")
	}

	corazaPath := filepath.Join(workdir, "nginx", "waf", "coraza.conf")
	data, err := os.ReadFile(corazaPath)
	if err != nil {
		return fmt.Errorf("reading coraza.conf: %w (run 'nself waf enable' first)", err)
	}

	content := string(data)
	var oldMode, newMode string
	if mode == "blocking" {
		oldMode = "SecRuleEngine DetectionOnly"
		newMode = "SecRuleEngine On"
	} else {
		oldMode = "SecRuleEngine On"
		newMode = "SecRuleEngine DetectionOnly"
	}

	if !strings.Contains(content, oldMode) {
		if strings.Contains(content, newMode) {
			ui.Info(fmt.Sprintf("WAF is already in %s mode.", mode))
			return nil
		}
		return fmt.Errorf("could not find SecRuleEngine directive in coraza.conf")
	}

	content = strings.Replace(content, oldMode, newMode, 1)
	if err := os.WriteFile(corazaPath, []byte(content), 0644); err != nil {
		return fmt.Errorf("writing coraza.conf: %w", err)
	}

	ui.Success(fmt.Sprintf("WAF mode set to %s.", mode))
	ui.Info("Run 'nself restart nginx' to apply.")
	return nil
}

func runWAFReport(cmd *cobra.Command, args []string) error {
	since, _ := cmd.Flags().GetString("since")

	ui.CommandHeader("nself waf report", fmt.Sprintf("WAF events (last %s)", since))

	cwd, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("getting working directory: %w", err)
	}
	workdir, err := config.FindNSelfRoot(cwd)
	if err != nil {
		return fmt.Errorf("no nself project found")
	}

	// Try to read WAF audit log from the nginx container.
	logCmd := exec.Command("docker", "compose", "exec", "nginx",
		"sh", "-c", "cat /var/log/nginx/waf_audit.log 2>/dev/null || echo 'No WAF audit log found'")
	logCmd.Dir = workdir
	logCmd.Stdout = os.Stdout
	logCmd.Stderr = os.Stderr
	if err := logCmd.Run(); err != nil {
		ui.Warn("Could not read WAF audit log. Is the WAF enabled?")
		return nil
	}

	return nil
}
